        <section>
            <h2>1. Controlador e operador</h2>
            <p>Para dados usados na administração da plataforma e no relacionamento com restaurantes assinantes, o Cardapim poderá atuar como controlador. Nas operações realizadas em nome dos restaurantes, como pedidos de consumidores quando esses módulos estiverem disponíveis, o restaurante poderá ser o controlador e o Cardapim o operador.</p>
            <p>O papel de cada parte deverá ser definido conforme a atividade e os contratos específicos, não apenas pelo nome da funcionalidade.</p>
        </section>
        <section>
            <h2>2. Categorias e finalidades</h2>
            <p>As categorias previstas incluem identificação de usuários, contatos, credenciais protegidas, dados cadastrais do estabelecimento, registros de auditoria e, futuramente, dados necessários à execução de pedidos, delivery ou atendimento. Cada finalidade deverá limitar-se aos dados necessários à operação correspondente.</p>
        </section>
        <section>
            <h2>3. Isolamento e segurança</h2>
            <p>A arquitetura do Cardapim prevê isolamento entre estabelecimentos, permissões por perfil, validação no servidor, proteção de senhas, HTTPS e registros de ações relevantes. Esses controles deverão ser testados por funcionalidade antes de cada liberação; o cadastro de uma tabela, isoladamente, não significa que o módulo operacional esteja pronto.</p>
        </section>
        <section>
            <h2>4. Fornecedores e integrações</h2>
            <p>Serviços de infraestrutura são necessários à hospedagem. Integrações com plataformas de pedidos, pagamentos e comunicação, como iFood, Asaas e WhatsApp, são planejadas; seus compartilhamentos e fornecedores efetivos deverão ser detalhados quando cada recurso entrar em funcionamento.</p>
        </section>
        <section>
            <h2>5. Direitos, retenção e incidentes</h2>
            <p>Solicitações dos titulares, correção e exclusão de dados deverão seguir a LGPD e os acordos aplicáveis entre as partes. Prazos de retenção observarão as necessidades operacionais e obrigações legais. Incidentes que exijam comunicação às autoridades e titulares serão tratados conforme a legislação e regulamentação vigentes.</p>
        </section>
        <section>
            <h2>6. Documentos complementares</h2>
            <p>O acordo específico de tratamento de dados entre o Cardapim e os restaurantes, incluindo instruções, responsabilidades, suboperadores e procedimentos de incidentes, deverá ser formalizado antes da operação contratual completa.</p>
